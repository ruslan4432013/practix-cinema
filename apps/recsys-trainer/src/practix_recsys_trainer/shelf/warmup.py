"""Прогрев горячего слоя после переключения указателя.

Списки и указатель кладутся ОДНОЙ ТРАНЗАКЦИЕЙ (``MULTI``/``EXEC``), и это
половина смысла ADR-004. Порядка двух отдельных команд здесь не хватало:
указатель, выставленный последним, действительно закрывал окно «выдача видит
новый номер версии, а ключей ещё нет», но открывал ровно обратное — сбой между
раскладкой списков и переводом указателя оставлял новые данные записанными, а
``recs:pointer`` смотрящим на старую версию. Указатель пишет только трейнер и
пишет его без TTL, так что «до следующего успешного прогрева» означает сутки
вчерашних рекомендаций при формально исправном сервисе. Внутри транзакции ни
одного из двух окон нет: применяется либо всё, либо ничего.

Указатель остаётся последней командой транзакции — читателю это уже безразлично
(промежуточного состояния не видит никто), но так не приходится объяснять
исключение из общего правила.

ЕСЛИ ТРАНЗАКЦИЯ ВСЁ-ТАКИ НЕ ПРОШЛА, устаревший указатель удаляется. Отсутствие
указателя — не авария: выдача спускается на ступень 2 своей лестницы и берёт
версию из PostgreSQL, где витрина уже опубликована и закоммичена. Это
«медленнее, но правильно» вместо «быстро и вчерашнее».

Старые ключи не удаляются вовсе. Они уходят по TTL, никого не разбудив, и
именно поэтому версия входит в ключ: массовое ``DEL`` между старой и новой
витриной — это тот же самый пик, только устроенный вручную.

Прогревается не всё, а верхушка: хвост каталога никто не запрашивает, а
``volatile-lru`` всё равно выселит непрошенное. Персональные ключи не
прогреваются совсем — их сотни тысяч, и попадание в конкретного пользователя
предсказать нельзя; они наполняются по промахам.

ОТКАЗ REDIS ЗДЕСЬ НЕ ОТМЕНЯЕТ ОБУЧЕНИЕ. Витрина уже в PostgreSQL и уже
опубликована; непрогретый кэш означает «первые запросы медленнее», а не
«обучение не состоялось».

НО НЕ ОТМЕНЯЕТ — НЕ ЗНАЧИТ «НЕ ВИДНО». Прогон, у которого не сложился прогрев,
завершается успешно, публикует версию и красит все метрики свежести в зелёное:
по наблюдаемым признакам он неотличим от здорового, хотя каждый запрос идёт в
PostgreSQL. Это ровно тот класс отказа, против которого написан F0.4, поэтому
исход прогрева уходит наружу дважды — в результат прогона (``TrainingResult``,
он же вывод ``cli train``) и в метрики цикла: счётчик неудач и гейдж
«обслуживает ли горячий слой актуальную версию» (``pointer_version``).
"""

import json
import logging

import redis

from practix_recsys_trainer.core.config import settings

logger = logging.getLogger(__name__)

POINTER_KEY = 'recs:pointer'


def _encode(items: list[tuple[str, float]]) -> str:
    """Тот же формат, что читает ``recommendations-api``: список пар."""
    return json.dumps([[film_id, score] for film_id, score in items])


def _connect() -> redis.Redis:
    """Один конструктор на оба обращения к горячему слою.

    Две копии этих шести строк разошлись бы молча: таймаут, поправленный в
    прогреве, но не в чтении указателя, никак себя не проявит, пока Redis
    отвечает.
    """
    return redis.Redis(
        host=settings.RECS_REDIS_HOST,
        port=settings.RECS_REDIS_PORT,
        db=settings.RECS_REDIS_DB,
        socket_timeout=settings.RECS_REDIS_TIMEOUT,
        socket_connect_timeout=settings.RECS_REDIS_TIMEOUT,
        decode_responses=True,
    )


def pointer_version() -> int | None:
    """На какую версию смотрит горячий слой. ``None`` — указателя нет или Redis молчит.

    Читается ИЗ REDIS, а не из результата прогона, ровно по той же причине, по
    которой возраст витрины берётся из PostgreSQL: гейдж, заполняемый только
    собственным прогоном демона, показывал бы «прогрето» ещё сутки после того,
    как горячий слой вычистили мимо трейнера. И наоборот — прогрев, чей ответ
    на ``EXEC`` потерялся по дороге, вернул ``False``, хотя данные легли;
    указатель об этом знает, а результат прогона нет.

    Молчащий Redis и отсутствующий указатель здесь одно и то же: и там и там
    горячий слой не обслуживает актуальную версию. Отличать их — работа
    ``recs_cache_unavailable_total`` у выдачи, которая ходит в Redis на каждом
    запросе, а не раз в тридцать секунд.
    """
    client = _connect()
    try:
        raw = client.get(POINTER_KEY)
    except Exception as exc:  # noqa: BLE001 — метрика не имеет права уронить цикл обучения
        logger.warning('POINTER UNREADABLE: %s', exc)
        return None
    finally:
        client.close()
    try:
        return int(raw) if raw is not None else None
    except ValueError:
        logger.warning('POINTER MALFORMED: %r', raw)
        return None


def warm(
    version: int,
    *,
    popular: list[tuple[str, float]],
    similar: dict[str, list[tuple[str, float]]],
) -> bool:
    """Раскладывает списки и переставляет указатель одной транзакцией. ``False`` — не сложилось."""
    client = _connect()
    try:
        # transaction=True (по умолчанию) — это MULTI/EXEC, а не просто пакет
        # команд в одном round-trip'е: раскладка списков и перевод указателя
        # применяются вместе или не применяются вовсе.
        pipe = client.pipeline()
        pipe.set(f'recs:v{version}:popular', _encode(popular), ex=settings.RECS_CACHE_TTL)

        warmed = 0
        for film_id, neighbours in similar.items():
            if warmed >= settings.RECS_TRAINER_WARMUP_FILMS:
                break
            pipe.set(f'recs:v{version}:similar:{film_id}', _encode(neighbours), ex=settings.RECS_CACHE_TTL)
            warmed += 1

        # Указатель — последней командой и БЕЗ TTL: он должен пережить любой
        # список. Истёкший указатель означал бы поход в базу за версией на
        # каждом запросе, то есть ровно ту нагрузку, от которой кэш и защищает.
        pipe.set(POINTER_KEY, str(version))
        pipe.execute()
        logger.info('Горячий слой прогрет: версия %s, фильмов %s', version, warmed)
        return True
    except Exception as exc:  # noqa: BLE001 — прогрев не имеет права отменить публикацию
        logger.warning('WARMUP FAILED: витрина опубликована, но кэш не прогрет (%s)', exc)
        _drop_stale_pointer(client, version)
        return False
    finally:
        client.close()


def _drop_stale_pointer(client: redis.Redis, version: int) -> None:
    """Убирает указатель, оставшийся смотреть на предыдущую версию.

    Указатель, не совпавший с только что опубликованной версией, хуже
    отсутствующего: выдача верит ему раньше, чем базе, и молча отдаёт
    вчерашние списки. Без указателя она берёт версию из PostgreSQL — источника
    истины, где витрина уже закоммичена.

    ``GET`` + ``DEL``, а не атомарная замена: писатель у витрины ровно один
    (``pg_advisory_lock``, раздел 5.3), гонки за этот ключ не существует по
    построению — в отличие от одноразовых тикетов гейтвея, где ``GETDEL``
    обязателен.

    Сравнение с версией, а не безусловный ``DEL``: если соединение оборвалось
    уже после того, как ``EXEC`` применился на сервере, указатель правильный, и
    сносить его значило бы гонять выдачу в базу впустую.
    """
    try:
        current = client.get(POINTER_KEY)
        if current is None or current == str(version):
            return
        client.delete(POINTER_KEY)
        logger.warning(
            'WARMUP FAILED: указатель %s снят, выдача возьмёт версию %s из PostgreSQL',
            current,
            version,
        )
    except Exception as exc:  # noqa: BLE001 — компенсация тем более не имеет права уронить обучение
        logger.warning('WARMUP FAILED: устаревший указатель снять не удалось (%s)', exc)
