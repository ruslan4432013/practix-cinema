"""Популярное — не украшение, а обязательный путь деградации.

ТЗ ставит холодный старт первой фичей (Ф1) не из-за простоты, а потому что это
путь деградации для двух остальных: пока его нет, любая незрелость модели
превращается в пустой экран. Поэтому популярное считается ВСЕГДА, даже когда
ни со-встречаемость, ни ALS не дали ни строки.

Основной источник — ClickHouse (число сеансов просмотра за окно). Но у него
есть отказ, при котором обучение всё равно должно закончиться чем-то: витрина
без популярного оставила бы выдачу без последней ступени лестницы. Поэтому есть
запасной путь — популярность по самой матрице взаимодействий, которая к этому
моменту уже прочитана.
"""

import numpy as np
from scipy import sparse


def from_matrix(matrix: sparse.csr_matrix, film_ids: list[str], *, limit: int) -> list[tuple[str, float]]:
    """Топ по числу зрителей в уже собранной матрице.

    Запасной путь на случай, когда отдельный запрос за популярным не удался, а
    матрица прочитана. Считается по числу НЕНУЛЕВЫХ элементов столбца, а не по
    сумме весов: сумма весов сделала бы популярным фильм, который мало кто
    смотрел, но досматривал целиком.
    """
    if matrix.shape[1] == 0:
        return []
    viewers = np.asarray((matrix > 0).sum(axis=0)).ravel()
    # Полная стабильная сортировка, а не argpartition: список короткий (сотни
    # позиций против миллионов пар у со-встречаемости), зато порядок при равном
    # числе зрителей определён индексом фильма. На свежем стенде равные счётчики
    # — не редкость, а норма, и без этого «популярное» менялось бы от прогона к
    # прогону на одних и тех же данных.
    ordered = np.argsort(-viewers, kind='stable')
    return [(film_ids[idx], float(viewers[idx])) for idx in ordered[:limit] if viewers[idx] > 0]
