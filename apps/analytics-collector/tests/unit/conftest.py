"""Настройка окружения юнит-тестов.

Правки ``sys.path`` здесь больше нет: коллектор — установленный пакет
(``practix-analytics-collector``), и его модули импортируются по полному имени
``practix_analytics_collector.*``. Прежняя версия подставляла путь к
``analytics_collector/src`` вручную, потому что сервис жил на ``PYTHONPATH``, а
имена его модулей (``core``, ``db``, ``models``) совпадали с именами в остальных
сервисах и не могли существовать на одном ``sys.path`` одновременно.

``UGC_ENV=test`` выставляется до импорта настроек: при ``prod`` конфигурация
отказывается стартовать с секретами по умолчанию, а юнит-тесты как раз работают
с ними.
"""

import os

os.environ.setdefault('UGC_ENV', 'test')
# Настройки читают .env, если он есть в рабочем каталоге. Для юнит-тестов это
# источник нестабильности: результат зависел бы от локального файла разработчика.
os.environ.setdefault('UGC_IP_HASH_SALT', 'unit-test-salt')
