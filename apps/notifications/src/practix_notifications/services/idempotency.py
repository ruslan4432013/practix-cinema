"""Ключи идемпотентности.

Брокер даёт гарантию «хотя бы один раз»: сообщение может приехать воркеру
повторно после переподключения, ребаланса или падения между отправкой письма и
``ack``. Превратить это в «ровно один раз» для пользователя может только
получатель — теория формулирует то же самое: «Сообщения должны обрабатываться
идемпотентно».

Ключ детерминирован и вычисляется из данных, а не выдаётся счётчиком: тогда
повторная попытка построит ТОТ ЖЕ ключ и упрётся в уникальный индекс.

ФОРМАТ СТАБИЛЕН и закреплён юнит-тестом: смена алгоритма задним числом сделала бы
все уже сохранённые задачи «новыми», и повторный запуск разослал бы всё заново.
"""

import hashlib

#: Длина hex-строки. 32 символа = 128 бит: коллизия невозможна на любых
#: мыслимых объёмах, а индекс вдвое компактнее полного sha256.
KEY_LENGTH = 32


def delivery_key(run_id: str, subscriber_id: str, channel: str) -> str:
    """Ключ одной доставки: (запуск, получатель, канал).

    Именно запуск, а не рассылка: повторяющаяся рассылка обязана дойти до того же
    человека и в следующую пятницу тоже.
    """
    raw = f'{run_id}:{subscriber_id}:{channel}'
    return hashlib.sha256(raw.encode('utf-8')).hexdigest()[:KEY_LENGTH]
