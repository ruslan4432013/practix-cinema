"""Ссылка подтверждения адреса для письма.

Живёт рядом с :mod:`practix_notifications.services.links` (ссылка отписки), чтобы
обе ссылки письма были в одном месте. Механика у них при этом разная, и разница
осознанная:

* отписка — САМОДОСТАТОЧНЫЙ подписанный токен (``TimestampSigner``), без таблицы:
  её длина никого не смущает, она живёт в подвале письма мелким шрифтом;
* подтверждение — КОРОТКИЙ КОД в чужом сервисе: задание требует ссылку, удобную
  на мобильном, а подписанный токен с UUID, меткой времени и целевым адресом
  занимает около двух сотен символов. Плюс по нему нужен счётчик визитов и
  возможность отзыва — и то, и другое требует строки в базе.

## Когда выпускается

В момент СБОРКИ письма, а не при регистрации в Auth. Три причины:

1. регистрация не должна получать зависимость от второго сервиса — она обязана
   завершиться, даже если про неё никто не услышит;
2. ``redirectUrl`` настраивается в панели рассылок, и Auth про него не знает;
3. срок жизни ссылки обязан начинаться от сборки: письмо, отложенное тихими
   часами, иначе приезжало бы уже протухшим.
"""

from practix_notifications.core.config import settings
from practix_notifications.services.shortener_client import ShortenerClient

#: Вид ссылки в шортенере. Именно он, а не маршрут, заставляет резолв сходить в
#: Auth перед редиректом.
KIND_CONFIRM_EMAIL = 'confirm_email'


def confirm_url(
    client: ShortenerClient,
    *,
    user_id: str,
    redirect_url: str = '',
    idempotency_key: str | None = None,
) -> str:
    """Короткая ссылка подтверждения адреса для указанного пользователя.

    ``redirect_url`` — куда увести ПОСЛЕ успешного подтверждения. Пусто —
    значение из настроек (по умолчанию главная страница кинотеатра, как и
    требует задание).

    ``idempotency_key`` берётся из ``DeliveryTask.idempotency_key``: он уже
    ``sha256(run:subscriber:channel)`` и уже уникален. Благодаря ему пересборка
    пачки не выпускает человеку вторую ссылку, а пересланное письмо содержит ту
    же самую — иначе два письма разошлись бы разными адресами, а счётчик визитов
    размазался бы по двум строкам.
    """
    return client.create_link(
        target_url=redirect_url or settings.NOTIFY_CONFIRM_REDIRECT_URL,
        kind=KIND_CONFIRM_EMAIL,
        user_id=user_id,
        ttl_hours=settings.NOTIFY_CONFIRM_LINK_TTL_HOURS,
        idempotency_key=idempotency_key,
    )
