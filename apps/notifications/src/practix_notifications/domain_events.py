"""Контракт фиксированных событий: обязательные поля, ключ дедупликации, контекст.

Модуль чистый — только stdlib, как и ``enums``. Его импортируют вью приёма,
сервис интейка и юнит-тесты, которым Django не нужен.

## Почему словарь живёт здесь, а не в общей библиотеке

Потребителей у него ровно два — Auth и django-admin, — и второй находится вне
uv-workspace (Python 3.12, свой ``uv.lock``) и импортировать пакет из workspace
физически не может: ``tools/check_graph_edges.py`` утверждает, что рёбер у
``django-admin`` нет вовсе. Библиотека, которую один из двух потребителей всё
равно продублирует строкой-литералом, — это не библиотека; ``docs/monorepo.md``
уже дважды отказал в извлечении по этой же причине.

В ``practix-contracts`` класть тем более нельзя: это словарь АНАЛИТИКИ (топики
Kafka, ключ партиционирования), его ``v1/`` заморожен собственным тестом, и
подмешивание туда AMQP-событий рассылок означало бы два несвязанных домена под
одним ``SCHEMA_VERSION``.

Поэтому: словарь здесь, продюсеры несут по одному строковому литералу, а
``tests/unit/test_domain_events.py`` сравнивает состав буквально — расширение
становится видимым в диффе, а не побочным эффектом.
"""

from typing import Any

#: Версия контракта приёма. Ломающее изменение — это новый префикс URL
#: (``/api/v2/notifications/events``), а не правка значений здесь.
INTAKE_SCHEMA_VERSION = 1

#: Поля, без которых событие не может быть обработано. Проверяются на приёме:
#: письмо, для которого нечем заполнить адрес, лучше не заводить вовсе, чем
#: обнаружить его в dead-letters через три перехода.
REQUIRED_DATA_FIELDS: dict[str, tuple[str, ...]] = {
    'user.registered': ('user_id', 'email'),
    'film.published': ('film_id', 'title'),
    'notification.direct': ('user_id',),
}

#: Поле, из которого строится ключ идемпотентности, — ПРИРОДНЫЙ ключ, а не
#: ``event_id``. Продюсер повторяет запрос при сетевой ошибке, и если он при этом
#: перегенерирует UUID события (а это самая обычная ошибка), дедупликация по
#: ``event_id`` пропустит второе приветственное письмо. Дедупликация по
#: ``user_id`` даёт одно письмо на человека по построению.
#:
#: Цена: триггер может объявить фильм ровно один раз. Это приемлемо — менеджер
#: по-прежнему запускает ту же рассылку руками, а ключ ручного запуска лежит в
#: другом пространстве имён (``services.scheduling.manual_run_key``).
NATURAL_KEY_FIELD: dict[str, str] = {
    'user.registered': 'user_id',
    'film.published': 'film_id',
}


def missing_fields(event_type: str, data: dict[str, Any]) -> tuple[str, ...]:
    """Каких обязательных полей не хватает в ``data``.

    Пустое значение считается отсутствующим: ``{'email': ''}`` — это не адрес.
    """
    required = REQUIRED_DATA_FIELDS.get(event_type, ())
    return tuple(field for field in required if not data.get(field))


def dedup_key(event_type: str, data: dict[str, Any], event_id: str) -> str:
    """Ключ, по которому повтор события не превращается во второе письмо."""
    natural = NATURAL_KEY_FIELD.get(event_type)
    if natural:
        return str(data[natural])
    return event_id


def event_run_key(event_type: str, key: str) -> str:
    """Ключ прогона для события.

    Префикс ``evt:`` отделяет пространство имён событий от ручных запусков
    (``{campaign_id}:manual:{timestamp}``) и от слотов расписания
    (``{schedule_id}:{local_time}``). Пересечение этих пространств означало бы,
    что событие может «съесть» слот расписания и наоборот.
    """
    return f'evt:{event_type}:{key}'


def context_from(event_type: str, data: dict[str, Any]) -> dict[str, Any]:
    """Переменные шаблона, которые несёт само событие.

    Только то, чего НЕТ в витрине подписчиков. ``login`` и ``email`` здесь
    намеренно отсутствуют даже для регистрации: веер кладёт их в переменные
    каждого получателя персонально, и они побеждают контекст прогона при
    рендере — дублировать их сюда значило бы завести второй источник правды,
    который ни на что не влияет.

    Ключи ограничены белым списком шаблонизатора
    (``content.models.DEFAULT_ALLOWED_VARIABLES``): переменная, которой нет в
    списке, не пройдёт валидацию шаблона у менеджера и останется мёртвой.
    """
    if event_type == 'film.published':
        context: dict[str, Any] = {'film_title': data['title']}
        year = data.get('year')
        if year:
            context['year'] = year
        return context
    return {}
