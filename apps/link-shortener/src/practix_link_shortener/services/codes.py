"""Генерация коротких кодов.

СЛУЧАЙНЫЙ base62, а не счётчик и не хэш цели. Разбор обоих отвергнутых
вариантов, потому что «как у bit.ly» здесь неверный ответ:

* **Счётчик, закодированный в base62.** Даёт самые короткие коды и ноль
  коллизий — и делает ссылки перечислимыми. Наша ссылка не рекламная: переход по
  ней ПОДТВЕРЖДАЕТ чужой адрес электронной почты. Перебор ``/s/aaaab…`` стал бы
  способом подтвердить ящик, к которому нет доступа.
* **Хэш от целевого адреса.** Детерминизм схлопывает двух пользователей с
  одинаковым ``redirectUrl`` в одну ссылку — то есть ломает и счёт визитов «по
  пользователю», и само подтверждение (кто именно перешёл?).

Источник случайности — ``secrets``, а не ``random``: ``random`` это Mersenne
Twister, чьё состояние восстанавливается по нескольким выданным значениям.
"""

import secrets
import string

#: base62: цифры и латиница обоих регистров. Ни '-', ни '_' — код диктуют
#: голосом и набирают руками с телефона, а дефис в конце строки почтовые клиенты
#: любят превращать в перенос.
ALPHABET = string.digits + string.ascii_letters

# 62^7 ≈ 3.5·10^12: при миллионе живых ссылок вероятность коллизии на одной
# вставке ≈ 3·10^-7, то есть повтор из-за неё — событие раз в жизни стенда, а не
# ветка, на которую можно не смотреть (она всё равно обработана).
DEFAULT_LENGTH = 7


def make_code(length: int = DEFAULT_LENGTH) -> str:
    """Случайный код указанной длины."""
    return ''.join(secrets.choice(ALPHABET) for _ in range(length))
