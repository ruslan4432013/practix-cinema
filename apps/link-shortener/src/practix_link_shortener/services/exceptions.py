"""Ошибки сервиса.

Деление проходит по одной линии: «виноват вызывающий» против «виновата
система». От неё зависит код ответа, а значит — поведение чужого цикла повторов.
"""


class InvalidTargetUrl(ValueError):
    """Целевой адрес не прошёл проверку. Терминальная: повтор не поможет."""


class CodeGenerationFailed(RuntimeError):
    """Не удалось подобрать свободный код за отведённое число попыток.

    Практически недостижимо при 62^7 вариантов, но молча зациклиться нельзя:
    это же исключение поймает и ошибку в различении ограничений.
    """


class ConfirmUnavailable(RuntimeError):
    """Auth недоступен или ответил 5xx.

    Ссылка ЖИВА, не работает система. Отсюда 503, а не 404: 404 сказал бы
    человеку «ваша ссылка протухла», и он бы её выбросил.
    """


class ConfirmRejected(RuntimeError):
    """Auth отказал по существу — пользователя нет.

    Ссылка указывает на кого-то, кого больше не существует; повторять нечего.
    """


class ConfirmMisconfigured(RuntimeError):
    """Auth ответил 401/403.

    Это не про пользователя, а про нашу служебную учётку: не заведена, не та
    роль, не тот пароль. Пользователю — 503, оператору — ERROR в лог.
    """
