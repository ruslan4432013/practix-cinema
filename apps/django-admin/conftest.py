"""Общая подготовка набора админки.

Здесь ровно одна вещь, и без неё юнит-тесты этого сервиса невозможны на SQLite.

## Схема `content` и трюк с кавычкой в `db_table`

Модели `movies` объявлены как `db_table = 'content"."genre'`. Кавычка внутри
имени — это инъекция схемы: Django оборачивает имя в кавычки и на Postgres
получается `"content"."genre"`, то есть таблица `genre` в схеме `content`.
Приём старый и рабочий, но опирается он на то, что СУБД понимает `схема.таблица`.

SQLite схем не знает — и провал тут не косметический, а двухступенчатый:

1. точку в `"content"."genre"` он читает как `база.таблица` и отвечает
   `unknown database "content"`;
2. присоединить базу с этим именем (`ATTACH DATABASE ... AS content`) можно, и
   таблицы начинают создаваться, — но внешние ключи в SQLite **не умеют
   ссылаться в другую базу**, поэтому `genre_film_work` с
   `REFERENCES "content"."genre"` падает следующей строкой. Тупик.

Поэтому схема здесь не подделывается, а снимается: в базе, где схем не бывает,
таблица называется просто `genre`. Правится это на `_meta.db_table` после
загрузки приложений и до создания таблиц.

## Почему это честно, а не «подгонка под зелёный»

Схема `content` — деталь размещения таблиц в Postgres, а не часть поведения,
которое проверяет набор: обработчик `post_save`, бэкенд аутентификации и
формирование события не знают о ней ничего. Настоящее размещение проверяет
стенд — контейнер `django-migrations` накатывает миграции (включая
`CREATE SCHEMA IF NOT EXISTS content`) на настоящий Postgres перед каждым
запуском сервиса.

Граница названа явно: **всё, что зависит от схемы, DDL или диалекта Postgres,
этому набору не принадлежит** — ему принадлежит логика на Python.
"""

import pytest

#: Инъекция схемы внутри `db_table`, ровно как она записана в моделях.
SCHEMA_PREFIX = 'content"."'


@pytest.hookimpl(trylast=True)
def pytest_configure(config: pytest.Config) -> None:
    """Снять префикс схемы со всех таблиц.

    `trylast`: `django.setup()` вызывает плагин pytest-django в своём
    `pytest_configure`, и до него реестра приложений ещё не существует.
    """
    from django.apps import apps

    for model in apps.get_models():
        meta = model._meta
        if meta.db_table.startswith(SCHEMA_PREFIX):
            meta.db_table = meta.db_table[len(SCHEMA_PREFIX) :]
