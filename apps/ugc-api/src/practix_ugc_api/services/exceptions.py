"""Доменные ошибки сервисного слоя.

В Auth сервисы бросают ``ValueError``, а роутер переводит его в 404. Здесь у
одной операции три разных исхода (нет рецензии, чужая рецензия, рецензия уже
есть), и один ``ValueError`` на всех заставил бы роутер разбирать текст
сообщения, чтобы выбрать код ответа. Три класса дешевле и надёжнее.
"""


class UgcError(Exception):
    """Базовая ошибка домена."""


class NotFoundError(UgcError):
    """Запрошенного объекта нет — 404."""


class ForbiddenError(UgcError):
    """Объект есть, но операция не разрешена этому пользователю — 403."""


class ConflictError(UgcError):
    """Операция противоречит уже существующему состоянию — 409."""
