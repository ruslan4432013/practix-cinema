"""Проверка доступности внешнего хранилища для проб и старта сервиса.

Извлечено из третьей копии. Одна и та же десятистрочная функция жила в
``ugc-api`` (денилист отозванных токенов) и появилась в ``recommendations-api``
сразу дважды — для горячего слоя витрины и для того же денилиста. Порог
дублирования в репозитории жёсткий (0.8%), и третья копия его пробила.

ЗАВИСИМОСТИ ОТ REDIS ЗДЕСЬ НЕТ НАМЕРЕННО. Функция утиная: ей нужен объект с
асинхронным ``ping()``, а не конкретный клиент. Поэтому она не тянет ни
``redis``, ни новую экстру в ``practix-core`` — и одинаково годится для любого
клиента с такой же пробой.

Настроек модуль не читает: ``practix_core`` не импортирует конфигурацию ни
одного сервиса (иначе замкнулся бы цикл через логгер), поэтому таймаут
передаётся аргументом.
"""

import asyncio
from typing import Protocol

# Во сколько раз собственный лимит времени больше таймаута сокета. Нужен именно
# ОТДЕЛЬНЫЙ лимит: redis-py повторяет неудачное соединение (по умолчанию три
# раза с джиттером), и на старте сервиса это растянуло бы запуск на секунды при
# недоступном хранилище — а проба готовности успела бы получить таймаут снаружи.
RETRY_ALLOWANCE = 3


class Pingable(Protocol):
    async def ping(self) -> object: ...


async def reachable(client: Pingable | None, timeout: float) -> bool:
    """Отвечает ли хранилище. Общая проверка для старта и пробы готовности.

    ``client is None`` — тот же исход, что и ошибка. Клиента не создали и
    клиент не отвечает — для вызывающего это одно и то же состояние, и
    разводить их значило бы заставлять каждую пробу проверять оба случая
    отдельно.

    Исключения не выпускаются наружу: назначение функции — ответить «да» или
    «нет», а не сообщить, каким именно способом хранилище недоступно. Причина
    пишется в лог вызывающим, если она ему нужна.
    """
    if client is None:
        return False
    try:
        async with asyncio.timeout(timeout * RETRY_ALLOWANCE):
            await client.ping()
    except Exception:  # noqa: BLE001 — любая ошибка здесь означает «недоступно»
        return False
    return True
