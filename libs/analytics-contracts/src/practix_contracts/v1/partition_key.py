"""Правило выбора ключа партиционирования — САМАЯ ценная из извлечённых деталей.

Правило было продублировано логически: метод ``EventEnvelope.partition_key`` у
коллектора (который ключ ПРОСТАВЛЯЕТ) и функция ``_partition_key`` у ETL (который
его ВОССТАНАВЛИВАЕТ, потому что у сообщений, пришедших в обход коллектора, ключ
может быть пустым, а поле нужно как ключ шардирования сырой таблицы).

Почему это опаснее остальных дублей: ключ определяет и партицию Kafka, и шард
ClickHouse. Разойдись эти две реализации — события одного пользователя поехали бы
в разные шарды, взаимный порядок сообщений перестал бы соблюдаться, а
``ReplacingMergeTree`` перестал бы схлопывать дубли, потому что дубли оказались бы
на разных узлах. Ни одно из этих последствий не выглядит как ошибка: запросы
продолжают работать и молча возвращают неверные числа.

И они УЖЕ немного расходились: коллектор проверял ``user_id is not None``, а ETL
— истинность (``if data.get('user_id')``). Практической разницы не было, потому
что ``user_id`` — это UUID либо ``None``, а UUID всегда истинен; но стоило полю
стать, скажем, целым, и ноль поехал бы в разные партиции у продюсера и
консьюмера. Здесь принят вариант по истинности: пустая строка и ноль — это
«идентификатора нет», а не «идентификатор равен нулю».
"""


def partition_key(
    user_id: object | None,
    anonymous_id: str | None,
    session_id: str | None,
) -> str:
    """``user_id`` -> ``anonymous_id`` -> ``session_id``, первое непустое.

    Порядок именно такой: аутентифицированный пользователь должен попадать в одну
    партицию независимо от устройства и сессии, анонимный — быть узнаваемым между
    сессиями по ``anonymous_id``, и только если нет ни того ни другого,
    группировкой остаётся сессия.
    """
    if user_id:
        return str(user_id)
    if anonymous_id:
        return str(anonymous_id)
    return str(session_id or '')
