#!/bin/sh
# Общий entrypoint всех пяти Python-сервисов. Было три файла: у двух совпадало
# всё кроме имени сервиса в комментарии, у третьего (auth) отсутствовал `set -e`.
#
# set -e ОБЯЗАТЕЛЕН. У настроек Auth есть обязательные поля без значений по
# умолчанию (PROJECT_NAME, JWT_SECRET_KEY, BASE_DIR, AUTHJWT_*). Без set -e
# неудавшийся `cp` ниже не остановил бы скрипт, и сервис стартовал бы, чтобы
# упасть на импорте с ValidationError — ошибка выглядела бы как проблема
# конфигурации, а не как отсутствующий .env.
set -e

# Если .env не пробросили, берём шаблон, чтобы сервис поднялся с разумными
# значениями по умолчанию. Сам .env в образ не попадает: он в .dockerignore.
if [ ! -f .env ]; then
  echo "Creating .env from .env.example"
  cp .env.example .env
fi

# Метрики нескольких воркеров uvicorn пишутся в mmap-файлы. Остатки от прошлого
# запуска нужно убрать: файлы умерших воркеров иначе продолжают отдаваться в
# скрейпе и показывают трафик, которого уже нет.
#
# Условие делает блок no-op для четырёх сервисов из пяти — переменную задаёт
# только образ коллектора.
if [ -n "$PROMETHEUS_MULTIPROC_DIR" ]; then
  mkdir -p "$PROMETHEUS_MULTIPROC_DIR"
  rm -f "$PROMETHEUS_MULTIPROC_DIR"/*.db 2>/dev/null || true
fi

exec "$@"
