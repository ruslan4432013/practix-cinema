"""Абстракция брокера событий.

Сервисный слой зависит от этого протокола, а не от ``aiokafka`` — тот же приём,
что и в ``rest/db/base.py`` (принцип инверсии зависимостей). Практическая
польза не теоретическая: в функциональных тестах на место продюсера
подставляется брокер-заглушка, который умеет «падать» по команде, и сценарий
деградации проверяется без остановки настоящего кластера Kafka.
"""

from abc import ABC, abstractmethod

from models.events import KafkaRecord


class BrokerUnavailableError(Exception):
    """Брокер недоступен. Событие следует увести в буфер деградации.

    Отдельный тип исключения нужен, чтобы отличать «инфраструктура недоступна,
    попробуем позже» от программной ошибки: первое — штатная ситуация с
    известной реакцией, второе — дефект, который нельзя маскировать.
    """


class RecordRejectedError(BrokerUnavailableError):
    """Брокер жив, но КОНКРЕТНУЮ запись принимать отказался.

    Наследование от ``BrokerUnavailableError`` не случайно: на горячем пути
    приёма реакция та же — увести событие в буфер, ответить 202 и не разбираться
    с причиной под нагрузкой. А вот дренаж буфера разницу видит и не тратит
    попытки: повторять запись, которую отвергли за её собственные свойства
    (размер, формат), бессмысленно — она сразу уезжает в DLQ.
    """


class EventBroker(ABC):
    """Транспорт публикации событий."""

    @abstractmethod
    async def publish(self, record: KafkaRecord) -> None:
        """Публикует запись.

        Возврат из метода означает, что запись принята транспортом, но ещё не
        обязательно подтверждена брокером. Ошибку подтверждения реализация
        обрабатывает асинхронно (см. ``brokers/kafka.py``).

        Бросает ``BrokerUnavailableError``, если запись не удалось даже принять.
        """

    @abstractmethod
    async def publish_now(self, record: KafkaRecord) -> None:
        """Публикует запись и дожидается подтверждения брокера.

        Используется фоновым дренажом: там важно узнать результат доставки до
        того, как запись будет удалена из буфера, иначе событие потерялось бы.
        """

    @property
    @abstractmethod
    def is_healthy(self) -> bool:
        """Считает ли транспорт себя работоспособным (для ``/health/ready``)."""
